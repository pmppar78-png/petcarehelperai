<p>Cats with chronic pain — arthritis especially — stop lying on their sides. They tuck, hunch, or loaf. They stop stretching after a nap. They develop a preferred side. If your cat has started hiding under furniture they used to sleep on top of, that's a signal even if nothing else has changed.</p>

